"""Generate an ed25519 key pair for signing Jiv updates.
Usage: python tools/gen_signing_key.py [--out /workspace/jiv-signing] [--embed]
  --embed  writes the PUBLIC key into jiv/update_key.py so this build trusts it.
The private key never goes into the app folder. Keep it secret and backed up."""
import argparse, os, sys
from pathlib import Path
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives import serialization

ap = argparse.ArgumentParser(); ap.add_argument("--out", default="/workspace/jiv-signing"); ap.add_argument("--embed", action="store_true")
ap.add_argument("--force", action="store_true"); a = ap.parse_args()
out = Path(a.out); out.mkdir(parents=True, exist_ok=True)
app = Path(__file__).resolve().parent.parent
if out.resolve() == app or app in out.resolve().parents: sys.exit("Refusing to write the private key inside the app folder.")
priv_p = out / "jiv_update_private.pem"
if priv_p.exists() and not a.force: sys.exit(f"{priv_p} exists (use --force to overwrite — old updates would stop verifying).")
k = Ed25519PrivateKey.generate()
priv_p.write_bytes(k.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption()))
os.chmod(priv_p, 0o600)
pub = k.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw).hex()
(out / "jiv_update_public.hex").write_text(pub + "\n")
print("private key:", priv_p); print("public key :", pub)
if a.embed:
    (app / "jiv" / "update_key.py").write_text(f'"""Public ed25519 key that signs official Jiv updates (generated by tools/gen_signing_key.py)."""\nPUBLIC_KEY_HEX = "{pub}"\n')
    print("embedded into jiv/update_key.py")
